// Regenerates crates/yusr-domain/src/hijri_table.rs from ICU's islamic-umalqura
// calendar, which carries the official Umm al-Qura data for 1300–1600 AH.
// Usage: node tools/gen_umalqura.js > crates/yusr-domain/src/hijri_table.rs
const FIRST_YEAR = 1300, LAST_YEAR = 1600;
const fmt = new Intl.DateTimeFormat("en-u-ca-islamic-umalqura", {
  timeZone: "UTC", year: "numeric", month: "numeric", day: "numeric",
});
const DAY = 86400000;
const parts = (day) => {
  const o = Object.fromEntries(fmt.formatToParts(new Date(day * DAY)).map((p) => [p.type, p.value]));
  return { y: +o.year, m: +o.month, d: +o.day };
};

let day = Date.UTC(1882, 0, 1) / DAY;
for (;;) {
  const p = parts(day);
  if (p.y === FIRST_YEAR && p.m === 1 && p.d === 1) break;
  day++;
}
const epoch = day;
const masks = [];
for (let y = FIRST_YEAR; y <= LAST_YEAR; y++) {
  let mask = 0;
  for (let m = 1; m <= 12; m++) {
    const start = day;
    do { day++; } while (parts(day).d !== 1);
    const len = day - start;
    if (len !== 29 && len !== 30) throw new Error(`bad month length ${y}/${m}: ${len}`);
    if (len === 30) mask |= 1 << (m - 1);
  }
  masks.push(mask);
}

const rows = [];
for (let i = 0; i < masks.length; i += 8) {
  rows.push("    " + masks.slice(i, i + 8).map((v) => `0x${v.toString(16).padStart(3, "0")}`).join(", ") + ",");
}
console.log(`// @generated by tools/gen_umalqura.js from ICU ${process.versions.icu}; do not edit by hand.

/// First Hijri year covered by [\`MONTH_LENGTHS\`].
pub const FIRST_YEAR: i32 = ${FIRST_YEAR};
/// Days since 1970-01-01 of 1 Muharram ${FIRST_YEAR} AH.
pub const EPOCH_DAYS: i64 = ${epoch};
/// One entry per Hijri year: bit \`m - 1\` set means month \`m\` has 30 days, otherwise 29.
pub const MONTH_LENGTHS: [u16; ${masks.length}] = [
${rows.join("\n")}
];`);
